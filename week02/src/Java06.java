public class Java06 {
    public static void main(String[] args) throws Exception {
        int age = 20;
        if(age >= 18) {
            System.out.println("You are an adult.");
        }
        else if(age >= 13) {
            System.out.println("You are a teenager.");
        }
        else {
            System.out.println("You are a child.");
        }
    }
}
